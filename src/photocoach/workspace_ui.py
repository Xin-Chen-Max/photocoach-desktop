"""Workspace presentation and widget construction. The window owns business callbacks."""
from PySide6.QtCore import Qt
from PySide6.QtWidgets import (QWidget, QVBoxLayout, QHBoxLayout, QLabel, QToolButton,
    QMenu, QPushButton, QSplitter, QProgressBar, QFrame, QDialog, QDialogButtonBox,
    QFormLayout, QComboBox, QCheckBox, QScrollArea, QTabWidget, QListWidget,
    QLineEdit, QSpinBox, QDoubleSpinBox, QMessageBox, QSizePolicy)
from .workspace_widgets import ToolSection, ParameterLabel
from .coach_view import CoachResponsePanel, ElidedLabel, QuestionInput
from .preview_view import ImageView, PhotoToolbar
from .histogram import HistogramView
from .edit_controls import EditSlider, DraftGainSpinBox
from .color_mixer_ui import ColorMixerEditor
from .color_grading_ui import ColorGradingEditor
from .curve import CurveEditor
from .lens_ui import LensEditor
from .detail_ui import DetailEditor
from .state import IDENTITY_CURVE
from .gradient_ui import GradientEditor,GradientController
from .spots_ui import SpotEditor, SpotController
from .snapshots_ui import SnapshotsPanel


def build_workspace(self) -> None:
    body = QWidget()
    body.setObjectName("appBody")
    layout = QVBoxLayout(body)
    layout.setContentsMargins(12, 10, 12, 8)
    layout.setSpacing(6)
    toolbar = QHBoxLayout()
    toolbar.setSpacing(7)
    title = QLabel("PhotoCoach")
    title.setObjectName("appTitle")
    title.setStyleSheet("font-weight:600;padding-right:6px")
    toolbar.addWidget(title)
    self.open_button = QToolButton()
    self.open_button.setText("Open")
    self.open_button.setPopupMode(QToolButton.ToolButtonPopupMode.MenuButtonPopup)
    open_menu = QMenu(self.open_button)
    self.open_raw_action = open_menu.addAction("Open RAW…", self.choose_raw)
    self.open_project_button = open_menu.addAction("Open project…", self.choose_project)
    self.open_button.setMenu(open_menu)
    self.open_button.clicked.connect(self.choose_raw)
    self.save_project_button = QPushButton("Save")
    self.save_project_button.clicked.connect(self.save_project)
    self.export_button = QPushButton("Export")
    self.export_button.setObjectName("exportAction")
    self.export_button.clicked.connect(self.choose_export)
    for button in (self.open_button, self.save_project_button):
        toolbar.addWidget(button)
    self.filename = ElidedLabel()
    self.filename.setText("No photo open")
    toolbar.addWidget(self.filename, 1)
    self.unsaved_label = QLabel("Unsaved changes")
    self.unsaved_label.setStyleSheet("color:#efc886")
    self.unsaved_label.hide()
    toolbar.addWidget(self.unsaved_label)
    self.photo_info_button = QPushButton("Info")
    self.photo_info_button.setToolTip("Dimensions and shooting information")
    self.photo_info_button.setCheckable(True)
    toolbar.addWidget(self.photo_info_button)
    self.lang_button = QPushButton("中文 / EN")
    self.lang_button.setCheckable(True)
    self.lang_button.setToolTip("Switch interface language between Chinese and English (切换中英双语界面)")
    self.lang_button.clicked.connect(self.toggle_language)
    toolbar.addWidget(self.lang_button)
    toolbar.addWidget(self.export_button)
    self.more_button = QToolButton()
    self.more_button.setText("More")
    self.more_button.setPopupMode(QToolButton.ToolButtonPopupMode.InstantPopup)
    more_menu = QMenu(self.more_button)
    more_menu.addAction("Preview details…", self._show_preview_details)
    self.report_button = more_menu.addAction("Save diagnostics…", self.save_diagnostics)
    self.more_button.setMenu(more_menu)
    toolbar.addWidget(self.more_button)
    self.connection_label = QLabel("Local processing · Mock coach")
    self.connection_label.setProperty("secondary", True)
    layout.addLayout(toolbar)
    top_divider = QFrame()
    top_divider.setFrameShape(QFrame.Shape.HLine)
    top_divider.setStyleSheet("color:#343434;")
    layout.addWidget(top_divider)
    self.workspace_splitter = QSplitter(Qt.Orientation.Vertical)
    self.workspace_splitter.setObjectName("workspaceSplitter")
    self.workspace_splitter.setChildrenCollapsible(False)
    self.workspace_splitter.setHandleWidth(8)
    splitter = self.editor_splitter = QSplitter()
    splitter.setChildrenCollapsible(False)
    self.preview = ImageView()
    self.preview.setObjectName("photoCanvas")
    image_panel = QWidget()
    image_panel.setObjectName("photoPanel")
    image_layout = QVBoxLayout(image_panel)
    image_layout.setContentsMargins(0, 0, 0, 0)
    def toolbar_group():
        group = QWidget()
        row = QHBoxLayout(group)
        row.setContentsMargins(0, 0, 0, 0)
        row.setSpacing(5)
        return group, row
    navigation, nav_row = toolbar_group()
    comparison, compare_row = toolbar_group()
    quality, quality_row = toolbar_group()
    self.fit_button = QPushButton("Fit")
    self.fit_button.clicked.connect(self.preview.fit)
    self.fit_button.setCheckable(True)
    self.actual_size_button = QPushButton("100%")
    self.actual_size_button.clicked.connect(lambda: self.preview.actual_size())
    self.actual_size_button.setCheckable(True)
    self.zoom_label = QLabel("Fit")
    self.zoom_label.setProperty("secondary", True)
    self.zoom_label.setFixedWidth(self.zoom_label.fontMetrics().horizontalAdvance('Fit · 800%')+6)
    self.detail_label = QLabel("Quick preview")
    self.detail_label.setProperty("secondary", True)
    self.detail_label.setFixedWidth(self.detail_label.fontMetrics().horizontalAdvance('Adjustment preview unavailable')+8)
    self.clipping=QPushButton('Clipping')
    self.clipping.setCheckable(True)
    self.clipping.setToolTip('Displayed SDR limits: red = any channel at 255; blue = all channels at 0. Reduced previews can miss small clipped regions. Not RAW clipping or recoverability. Overlays are never exported or sent to AI.')
    self.retry_detail_button = QPushButton("Retry detail")
    self.retry_detail_button.clicked.connect(self.request_detail)
    self.retry_detail_button.hide()
    for widget in (self.fit_button, self.actual_size_button, self.zoom_label):
        nav_row.addWidget(widget)
    self.compare = QPushButton("Baseline")
    self.compare.setCheckable(True)
    self.compare.setToolTip("Camera white balance and neutral tone/color through this RAW pipeline, keeping the current crop, angle and distortion; neutral vignetting for aligned comparison; not the camera JPEG.")
    self.compare.toggled.connect(self.change_compare)
    self.edited_button = QPushButton("Edited")
    self.edited_button.setCheckable(True)
    self.edited_button.setChecked(True)
    self.edited_button.clicked.connect(lambda: self.change_compare(False))
    compare_row.addWidget(self.compare)
    compare_row.addWidget(self.edited_button)
    self.composition_button = QPushButton("Crop / Straighten")
    self.composition_button.setToolTip("Crop and straighten (rotate up to ±15°). Non-destructive; the original RAW is never modified.")
    self.composition_button.clicked.connect(self.open_composition)
    compare_row.addWidget(self.composition_button)
    self.detail_busy = QProgressBar()
    self.detail_busy.setRange(0, 0)
    self.detail_busy.setTextVisible(False)
    self.detail_busy.setFixedSize(42, 5)
    busy_policy=self.detail_busy.sizePolicy()
    busy_policy.setRetainSizeWhenHidden(True)
    self.detail_busy.setSizePolicy(busy_policy)
    self.detail_busy.hide()
    for widget in (self.clipping, self.detail_busy, self.detail_label, self.retry_detail_button):
        quality_row.addWidget(widget)
    self.photo_toolbar = PhotoToolbar(navigation, comparison, quality)
    image_layout.addWidget(self.photo_toolbar)
    image_layout.addWidget(self.preview, 1)
    hint = self.canvas_hint_label = QLabel("Ctrl + wheel: zoom · Space + drag: pan · Double-click: Fit / 100%")
    hint.setStyleSheet("color:#ababab;font-size:12px")
    hints = QHBoxLayout()
    hints.addWidget(hint, 1)
    self.view_notice = QLabel()
    self.view_notice.setStyleSheet("color:#79afff;font-size:12px")
    hints.addWidget(self.view_notice)
    image_layout.addLayout(hints)
    self.preview.viewChanged.connect(self._view_changed)
    self.preview.statusChanged.connect(self._view_status)
    splitter.addWidget(image_panel)
    panel = QFrame()
    panel.setObjectName("editPanel")
    panel.setMinimumWidth(0)
    side = QVBoxLayout(panel)
    self.metadata_label = QLabel("Dimensions and shooting information appear after decoding.")
    self.metadata_label.setWordWrap(True)
    self.metadata_label.setTextFormat(Qt.TextFormat.PlainText)
    self.photo_info = QDialog(self)
    self.photo_info.setWindowTitle("Photo information")
    self.photo_info.resize(460, 260)
    info_layout = QVBoxLayout(self.photo_info)
    info_layout.addWidget(self.metadata_label)
    info_close = QDialogButtonBox(QDialogButtonBox.StandardButton.Close)
    info_close.rejected.connect(self.photo_info.reject)
    info_layout.addWidget(info_close)
    def show_info(visible):
        self.photo_info.setVisible(visible)
    self.photo_info_button.toggled.connect(show_info)
    self.photo_info.finished.connect(lambda: self.photo_info_button.setChecked(False))
    self.undo_button = QPushButton("Undo")
    self.redo_button = QPushButton("Redo")
    self.reset_button = QPushButton("Reset edits")
    self.reset_button.setProperty("compact", True)
    self.undo_button.clicked.connect(self.undo)
    self.redo_button.clicked.connect(self.redo)
    self.reset_button.clicked.connect(self.reset_edits)
    toolbar.insertWidget(3, self.undo_button)
    toolbar.insertWidget(4, self.redo_button)
    self.histogram = HistogramView(compact=True)
    side.addWidget(self.histogram)
    self.base_rendering = QComboBox()
    for title, mode in (("Natural / As Shot", "natural_v1"), ("Neutral / Flat", "neutral_v1"), ("Legacy", "legacy_v1")):
        self.base_rendering.addItem(title, mode)
    self.base_rendering.setCurrentIndex(0)
    self.base_rendering.setAccessibleName("Base rendering")
    self.base_rendering.setToolTip("As-shot white balance and camera color conversion; a fixed baseline look, separate from creative sliders.")
    self.base_rendering.currentIndexChanged.connect(self._base_rendering_changed)
    self.base_rendering_label = QLabel("Base rendering")
    base_row = QHBoxLayout()
    base_row.addWidget(self.base_rendering_label)
    base_row.addWidget(self.base_rendering, 1)
    side.addLayout(base_row)
    self.light_section = ToolSection("Light", True)
    # Second entry point to the same crop/straighten dialog as the photo toolbar.
    self.crop_section = ToolSection("Crop and straighten")
    self.crop_summary = QLabel("Full frame · Angle +0.00°")
    self.crop_summary.setProperty("secondary", True)
    self.crop_summary.setTextFormat(Qt.TextFormat.PlainText)
    self.crop_section.content.addWidget(self.crop_summary)
    crop_row = QHBoxLayout()
    self.crop_open_button = QPushButton("Crop and straighten…")
    self.crop_open_button.setProperty("compact", True)
    self.crop_open_button.setToolTip("Open the crop and straighten editor (rotate up to ±15°).")
    self.crop_open_button.clicked.connect(self.open_composition)
    self.crop_reset_button = QPushButton("Reset")
    self.crop_reset_button.setProperty("compact", True)
    self.crop_reset_button.setToolTip("Restore the full frame and 0° angle. One Undo step.")
    self.crop_reset_button.clicked.connect(self.reset_composition)
    crop_row.addWidget(self.crop_open_button, 1)
    crop_row.addWidget(self.crop_reset_button)
    self.crop_section.content.addLayout(crop_row)
    self.lens_section = ToolSection("Lens corrections")
    self.lens_editor = LensEditor()
    self.lens_section.content.addWidget(self.lens_editor)
    self.lens_editor.gestureStarted.connect(lambda: self._begin_parameter_gesture("lens_corrections"))
    self.lens_editor.gestureEnded.connect(self._finish_gesture)
    self.lens_editor.valuesChanged.connect(lambda values: self.change_parameter("lens_corrections", values))
    self.lens_editor.resetRequested.connect(lambda values: self.change_parameter("lens_corrections", values, sync=True))
    self.detail_section = ToolSection("Detail")
    self.detail_editor = DetailEditor()
    self.detail_section.content.addWidget(self.detail_editor)
    self.detail_editor.gestureStarted.connect(lambda: self._begin_parameter_gesture("detail"))
    self.detail_editor.gestureEnded.connect(self._finish_gesture)
    self.detail_editor.valuesChanged.connect(lambda values: self.change_parameter("detail", values))
    self.detail_editor.resetRequested.connect(lambda values: self.change_parameter("detail", values, sync=True))
    self.local_section = ToolSection('Local adjustments')
    self.local_gradients=GradientEditor()
    self.local_section.content.addWidget(self.local_gradients)
    self.local_controller=GradientController(self,self.local_gradients)
    self.spots_section = ToolSection("Spot removal")
    self.spots_editor = SpotEditor()
    self.spots_section.content.addWidget(self.spots_editor)
    self.spots_controller = SpotController(self, self.spots_editor)
    self.color_section = ToolSection("Color")
    self.curve_section = ToolSection("Curve")
    for section in (self.light_section, self.crop_section, self.lens_section, self.detail_section, self.local_section, self.spots_section, self.color_section, self.curve_section):
        side.addWidget(section)
    light = self.light_section.content
    color = self.color_section.content
    curve = self.curve_section.content
    self.exposure_label = ParameterLabel("Exposure  +0.00 EV")
    light.addWidget(self.exposure_label)
    self.exposure_slider = EditSlider(Qt.Orientation.Horizontal)
    self.exposure_slider.setRange(-500, 500)
    self.exposure_slider.sliderPressed.connect(lambda: self._begin_parameter_gesture("exposure_ev"))
    self.exposure_slider.sliderReleased.connect(self._finish_gesture)
    self.exposure_slider.valueChanged.connect(self.change_exposure)
    light.addWidget(self.exposure_slider)
    form = QFormLayout()
    self.wb_form = form
    self.wb_mode = QComboBox()
    self.wb_mode.setSizeAdjustPolicy(QComboBox.SizeAdjustPolicy.AdjustToMinimumContentsLengthWithIcon)
    self.wb_mode.setMinimumContentsLength(10)
    self.wb_mode.addItems(["Camera", "Custom · sensor RGB gains"])
    self.wb_mode.currentIndexChanged.connect(self._wb_mode_changed)
    self.wb_label = QLabel("White balance")
    form.addRow(self.wb_label, self.wb_mode)
    self.balance_sliders = []
    self.balance_labels = []
    for name, limit in (("Warmth", 200), ("Tint", 400)):
        label = ParameterLabel()
        slider = EditSlider(Qt.Orientation.Horizontal)
        slider.setRange(-limit, limit)
        slider.setToolTip("Draft only: apply white balance to process RAW. Relative sensor balance in stops, not calibrated Kelvin. Positive warmth favors red over blue; positive tint favors magenta over green.")
        self.balance_labels.append(label)
        self.balance_sliders.append(slider)
        form.addRow(label)
        form.addRow(slider)
    self.balance_sliders[0].valueChanged.connect(self._balance_draft_changed)
    self.balance_sliders[1].valueChanged.connect(self._balance_draft_changed)
    self.advanced_wb = QCheckBox("Advanced RGB gains")
    form.addRow(self.advanced_wb)
    self.gains = []
    for label in ("Red R", "Green G", "Blue B"):
        spin = DraftGainSpinBox()
        spin.setRange(0.25, 4.0)
        spin.setDecimals(3)
        spin.setSingleStep(0.025)
        spin.setValue(1.0)
        spin.setEnabled(False)
        form.addRow(label, spin)
        self.gains.append(spin)
    self.advanced_wb.toggled.connect(self._wb_form_enabled)
    for spin in self.gains:
        spin.valueChanged.connect(self._gain_draft_changed)
    color.addLayout(form)
    self.wb_hint = QLabel("Choose Camera WB, or adjust Warmth / Tint then Apply. No Kelvin calibration.")
    self.wb_hint.setWordWrap(True)
    self.wb_hint.setFixedHeight(self.wb_hint.fontMetrics().lineSpacing() * 3)
    self.wb_hint.setAlignment(Qt.AlignmentFlag.AlignTop)
    color.addWidget(self.wb_hint)
    self.apply_wb = QPushButton("Apply white balance")
    self.apply_wb.setProperty("compact", True)
    self.apply_wb.setToolTip("A new white balance requires RAW processing. Input changes apply only on click.")
    self.apply_wb.clicked.connect(self.change_wb)
    color.addWidget(self.apply_wb)
    self.pick_wb = QPushButton("Pick neutral white balance")
    self.pick_wb.setProperty("compact", True)
    self.pick_wb.setCheckable(True)
    self.pick_wb.setToolTip("Click an evenly lit matte gray or white patch. Samples original Bayer sensor values, then applies one WB edit. Avoid colored, dark or clipped patches. Esc cancels.")
    self.pick_wb.toggled.connect(self._pick_wb_toggled)
    self.preview.neutralPicked.connect(self._sample_wb)
    self.preview.pickerCancelled.connect(lambda: self.pick_wb.setChecked(False))
    color.addWidget(self.pick_wb)
    self.adjustment_sliders = {}
    self.adjustment_labels = {}
    for name, label, low, high, initial in (("highlights", "Highlights", -100, 100, 0),
                                           ("shadows", "Shadows", -100, 100, 0),
                                           ("whites", "Whites", -100, 100, 0),
                                           ("blacks", "Blacks", -100, 100, 0),
                                           ("contrast", "Contrast", -100, 100, 0),
                                           ("vibrance", "Vibrance", -100, 100, 0),
                                           ("saturation", "Saturation", 0, 200, 100)):
        text = ParameterLabel(f"{label}  {initial / 100:.2f}")
        slider = EditSlider(Qt.Orientation.Horizontal)
        slider.setRange(low, high)
        slider.setValue(initial)
        if name in ("highlights", "shadows"):
            slider.setToolTip("Global luminance-weighted adjustment: positive lifts, negative darkens, zero is neutral. Applied before SDR clipping. Cannot recover information already clipped by the RAW decoder.")
        if name in ("whites", "blacks"):
            slider.setToolTip("Shared RGB endpoint shaping: positive lifts, negative darkens. Whites affects upper tones; Blacks lower tones. Zero is neutral. Cannot recover clipped RAW data.")
        if name == "vibrance":
            slider.setToolTip("Affects muted colors more than already saturated colors. Zero is neutral. No skin detection or masks.")
        slider.sliderPressed.connect(lambda name=name: self._begin_parameter_gesture(name))
        slider.sliderReleased.connect(self._finish_gesture)
        slider.valueChanged.connect(lambda value, name=name: self.change_parameter(name, value / 100))
        self.adjustment_sliders[name] = slider
        self.adjustment_labels[name] = text
        group = color if name in ("vibrance", "saturation") else light
        group.addWidget(text)
        group.addWidget(slider)
    for name in ("contrast", "highlights", "shadows", "whites", "blacks"):
        light.addWidget(self.adjustment_labels[name])
        light.addWidget(self.adjustment_sliders[name])
    self.color_mixer = ColorMixerEditor()
    self.color_mixer.gestureStarted.connect(lambda: self._begin_parameter_gesture("color_mixer"))
    self.color_mixer.gestureEnded.connect(self._finish_gesture)
    self.color_mixer.valuesChanged.connect(lambda values: self.change_parameter("color_mixer", values))
    self.color_mixer.resetRequested.connect(lambda values: self.change_parameter("color_mixer", values, sync=True))
    color.addWidget(self.color_mixer)
    self.color_grading = ColorGradingEditor()
    self.color_grading.gestureStarted.connect(lambda: self._begin_parameter_gesture("color_grading"))
    self.color_grading.gestureEnded.connect(self._finish_gesture)
    self.color_grading.valuesChanged.connect(lambda values: self.change_parameter("color_grading", values))
    self.color_grading.resetRequested.connect(lambda values: self.change_parameter("color_grading", values, sync=True))
    color.addWidget(self.color_grading)
    self.curve_label = QLabel("Shared RGB curve")
    self.curve_label.setToolTip("Double-click to add a point; drag to adjust; Delete to remove. Hover for Input / Output values.")
    curve.addWidget(self.curve_label)
    self.curve = CurveEditor()
    self.curve.gestureStarted.connect(lambda: self._begin_parameter_gesture("rgb_curve"))
    self.curve.pointsChanged.connect(lambda points: self.change_parameter("rgb_curve", points))
    self.curve.gestureEnded.connect(self._finish_gesture)
    curve.addWidget(self.curve)
    self.reset_curve_button = QPushButton("Reset curve")
    self.reset_curve_button.setProperty("compact", True)
    self.reset_curve_button.clicked.connect(lambda: self.change_parameter("rgb_curve", IDENTITY_CURVE, sync=True))
    curve.addWidget(self.reset_curve_button)
    self.version_label = QLabel("State — / Preview —")
    self.preview_details = QDialog(self)
    self.preview_details.setWindowTitle("Preview details")
    diagnostic_layout = QVBoxLayout(self.preview_details)
    diagnostic_layout.addWidget(self.version_label)
    self.render_details = QLabel("No preview rendered yet.")
    self.render_details.setWordWrap(True)
    diagnostic_layout.addWidget(self.render_details)
    close_details = QDialogButtonBox(QDialogButtonBox.StandardButton.Close)
    close_details.rejected.connect(self.preview_details.hide)
    diagnostic_layout.addWidget(close_details)
    side.addStretch()
    divider = QFrame()
    divider.setFrameShape(QFrame.Shape.HLine)
    divider.setStyleSheet("color:#3a3a3a;")
    side.addWidget(divider)
    self.reset_button.setToolTip("Reset all image parameters in one undo step")
    help_button = self.help_button = QPushButton("Editing help")
    help_button.setProperty("compact", True)
    help_button.clicked.connect(lambda: QMessageBox.information(self, "Editing help",
        "Fit shows the whole photo. 100% uses one image pixel per physical display pixel.\n"
        "Ctrl + wheel zooms under the pointer; Space + drag pans.\n\n"
        "Baseline uses camera white balance and neutral tone/color, keeping crop, angle and distortion; vignetting is neutral. It is not the camera JPEG.\n"
        "SDR sRGB; monitor ICC conversion remains unverified. Lowering exposure cannot recover decoder-clipped data."))
    side_footer = QHBoxLayout()
    side_footer.setSpacing(6)
    side_footer.addWidget(self.reset_button, 1)
    side_footer.addWidget(help_button, 1)
    side.addLayout(side_footer)
    self.edit_scroll = QScrollArea()
    self.edit_scroll.setWidgetResizable(True)
    self.edit_scroll.setVerticalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOn)
    self.edit_scroll.setHorizontalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOff)
    self.edit_scroll.setWidget(panel)
    self.tabs = QTabWidget()
    self.tabs.setMinimumWidth(320)
    self.tabs.addTab(self.edit_scroll, "Edit")
    history_panel = QWidget()
    history_layout = QVBoxLayout(history_panel)
    history_layout.setContentsMargins(6, 6, 6, 6)
    history_layout.setSpacing(6)
    self.snapshots_panel = SnapshotsPanel()
    self.snapshots_panel.saveRequested.connect(self.save_named_snapshot)
    self.snapshots_panel.restoreRequested.connect(self.restore_named_snapshot)
    self.snapshots_panel.deleteRequested.connect(self.delete_named_snapshot)
    self.snapshots_panel.compareToggled.connect(self.change_compare_snapshot)
    history_layout.addWidget(self.snapshots_panel)
    history_divider = QFrame()
    history_divider.setFrameShape(QFrame.Shape.HLine)
    history_divider.setStyleSheet("color:#383838;")
    history_layout.addWidget(history_divider)
    history_note = self.history_note = QLabel("Committed actions · Complete audit is saved in the project")
    history_note.setWordWrap(True)
    history_note.setProperty("secondary", True)
    history_layout.addWidget(history_note)
    self.history_list = QListWidget()
    history_layout.addWidget(self.history_list, 1)
    self.history_summary = QLabel("No edits")
    self.history_summary.setProperty("secondary", True)
    history_layout.addWidget(self.history_summary)
    self.tabs.addTab(history_panel, "History")
    splitter.addWidget(self.tabs)
    splitter.setStretchFactor(0, 1)
    splitter.setStretchFactor(1, 0)
    splitter.setSizes([900, 344])
    self.workspace_splitter.addWidget(splitter)
    self.coach_panel = self._build_coach_panel()
    self.workspace_splitter.addWidget(self.coach_panel)
    self.workspace_splitter.handle(1).setToolTip("Drag to resize the coach area.")
    self.workspace_splitter.setStretchFactor(0, 1)
    self.workspace_splitter.setStretchFactor(1, 0)
    self.workspace_splitter.setSizes([470, self._expanded_coach_height])
    layout.addWidget(self.workspace_splitter, 1)
    footer = QHBoxLayout()
    self.status = QLabel("Ready · Originals are read-only. Outputs require a new filename.")
    self.status.setObjectName("statusLabel")
    self.status.setWordWrap(True)
    self.status.setMinimumHeight(self.status.fontMetrics().lineSpacing())
